// Interacción real con Livewire/Laravel contra fixtures de la prueba PHPUnit; nunca contra la instalación operativa.
import {mkdirSync,writeFileSync,existsSync} from 'node:fs';
import {join} from 'node:path';
import assert from 'node:assert/strict';
import puppeteer from 'puppeteer';
const base=process.env.RM_MEDICATION_HTTP_BASE, evidence=process.env.RM_MEDICATION_EVIDENCE_DIR;
if(!/^http:\/\/127\.0\.0\.1:\d+$/.test(base||'')||!evidence) throw new Error('Falta el servidor aislado y la carpeta de evidencia.');
mkdirSync(evidence,{recursive:true});
const executablePath=[process.env.PUPPETEER_EXECUTABLE_PATH,await puppeteer.executablePath(),'C:/Program Files/Google/Chrome/Application/chrome.exe'].find(path=>path&&existsSync(path));
if(!executablePath){process.stdout.write('SKIP: no hay navegador instalado.\n');process.exit(77);}
const browser=await puppeteer.launch({headless:true,executablePath}),page=await browser.newPage(), errors=[];
const failures=[];page.on('response',response=>{if(response.status()>=400)failures.push({url:response.url(),status:response.status()});});
page.setDefaultTimeout(18000);page.on('pageerror',error=>errors.push(error.message));
const waitIdle=()=>page.waitForNetworkIdle({idleTime:350,timeout:18000});
const fill=async(selector,value)=>{await page.focus(selector);await page.keyboard.down('Control');await page.keyboard.press('KeyA');await page.keyboard.up('Control');await page.type(selector,value);await page.$eval(selector,el=>el.dispatchEvent(new Event('change',{bubbles:true})));await waitIdle();};
const click=async(selector)=>{await page.click(selector);await waitIdle();};
try {
    await page.setViewport({width:1440,height:1000});
    await page.goto(base+'/__qa/medication',{waitUntil:'networkidle0'});
    await click('#qa-open');
    await page.waitForSelector('.rm-medication__dose-select');
    await click('button[wire\\:click="seleccionarDosis(\'HPR_TEST_01\')"]');
    await page.waitForSelector('.rm-medication-media__photo');
    assert.ok(await page.$eval('.rm-medication-media__photo',el=>el.complete&&el.naturalWidth>0),'Foto de catálogo cargada');
    await click('input[name="resultado"][value="ADMINISTRADA"]');
    await page.waitForSelector('#med-hora-real');
    await click('button[wire\\:click="usarHoraActual"]');
    assert.equal(await page.$eval('#med-hora-real',el=>el.value),'09:00');
    await fill('#med-dosis-real','49.125');
    await click('button[wire\\:click="solicitarSalida(\'limpiar\')"]');
    await page.waitForSelector('.rm-medication__discard');
    await click('button[wire\\:click="cancelarConfirmacion"]');
    assert.equal(await page.$eval('#med-dosis-real',el=>el.value),'49.125');
    await click('button[wire\\:click="verImagen"]');
    await page.waitForSelector('.rm-medication__image-dialog.is-open');
    await page.screenshot({path:join(evidence,'browser-imagen-1440.png')});
    await click('button[wire\\:click="cerrarImagen"]');
    assert.equal(await page.$eval('#med-dosis-real',el=>el.value),'49.125');
    await page.screenshot({path:join(evidence,'browser-captura-1440.png')});
    await click('button[type="submit"][form="formAdministracion"]');
    await page.waitForSelector('.rm-medication__saved');
    assert.match(await page.$eval('.rm-medication__confirmation',el=>el.innerText),/49\.125/);
    await page.screenshot({path:join(evidence,'browser-guardado-1440.png')});
    await click('button[wire\\:click="abrirHistorial"]');await click('button[wire\\:click="abrirEvolucion"]');
    await page.waitForFunction(()=>document.querySelectorAll('.rm-signos__graph-popup:popover-open').length===2);
    await page.waitForFunction(()=>window.RMCharts.has('medication-results-chart'));
    assert.equal(await page.evaluate(()=>window.RMCharts.get('medication-results-chart').data.datasets[0].data[0]),1);
    await page.screenshot({path:join(evidence,'browser-consultas-1440.png')});
    await click('#medicacion-evolucion [aria-label="Cerrar evolucion"]');
    await click('#medicacion-historial [aria-label="Cerrar historial"]');
    await click('button[wire\\:click="prepararSiguienteDosis"]');
    assert.equal(await page.$$eval('input[name="resultado"]:checked',els=>els.length),0);
    assert.ok(await page.$eval('button[type="submit"][form="formAdministracion"]',el=>el.disabled));
    await page.setViewport({width:390,height:950});await page.reload({waitUntil:'networkidle0'});await click('#qa-open');
    await click('button[wire\\:click="seleccionarDosis(\'HPR_BROWSER_02\')"]');
    await page.$eval('.rm-medication__medication',el=>el.scrollIntoView({block:'start'}));
    await page.screenshot({path:join(evidence,'browser-imagen-390.png')});
    await click('input[name="resultado"][value="OMITIDA"]');await fill('#med-motivo','Captura sintética pendiente');
    await click('button[wire\\:click="solicitarSalida(\'cerrar\')"]');await page.waitForSelector('.rm-medication__discard');
    await click('button[wire\\:click="cancelarConfirmacion"]');
    assert.equal(await page.$eval('#med-motivo',el=>el.value),'Captura sintética pendiente');
    await page.screenshot({path:join(evidence,'browser-omision-390.png')});
    assert.deepEqual(errors,[]);
    writeFileSync(join(evidence,'browser-resultados.json'),JSON.stringify({livewireHttp:true,desktop:true,mobile:true,photo:true,discard:true,saved:true,windows:true,errors},null,2));
    process.stdout.write('PASS: Livewire HTTP, imagen, botones, captura, consultas y móvil.\n');
} catch(error) {
    await page.screenshot({path:join(evidence,'browser-failure.png')});
    writeFileSync(join(evidence,'browser-failure.html'),await page.content());
    process.stderr.write(JSON.stringify({errors,failures,body:(await page.$eval('body',el=>el.innerText)).slice(0,700)})+'\n');
    throw error;
} finally {await browser.close();}
