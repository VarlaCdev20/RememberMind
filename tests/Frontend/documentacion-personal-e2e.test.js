import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { createServer } from 'node:net';
import { randomBytes } from 'node:crypto';
import { writeFile, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import puppeteer from 'puppeteer';

test('documentación del personal: biblioteca, filtros y vista previa responsive', { skip: process.env.RM_DOCUMENTACION_E2E !== '1', timeout: 240000 }, async t => {
    const root = fileURLToPath(new URL('../../', import.meta.url));
    const output = path.join(root, 'output', 'documentacion-personal-20261105');
    await mkdir(output, { recursive: true });
    const db = path.join(tmpdir(), `remembermind-gerencia-${randomBytes(8).toString('hex')}_testing.sqlite`);
    await writeFile(db, '', { flag: 'wx', mode: 0o600 });
    const port = await new Promise(resolve => { const s = createServer().listen(0, '127.0.0.1', () => { const p = s.address().port; s.close(() => resolve(p)); }); });
    const base = `http://127.0.0.1:${port}`;
    const token = randomBytes(24).toString('hex');
    const env = { ...process.env, APP_ENV: 'testing', APP_URL: base, RM_GERENCIA_QA_DB: db, RM_GERENCIA_QA_TOKEN: token, RM_GERENCIA_QA_AMPLIACION: '1', RM_GERENCIA_QA_ARCHIVOS: '1' };
    const router = 'tests/Support/ServidorGerenciaSintetico.php';
    const prepared = await new Promise((resolve, reject) => {
        const c = spawn('php', [router, '--preparar'], { cwd: root, env, windowsHide: true });
        let out = ''; c.stdout.on('data', b => out += b); c.stderr.on('data', b => out += b);
        c.on('error', reject); c.on('close', code => code ? reject(new Error(out)) : resolve(out));
    });
    assert.match(prepared, /PREPARADO/);
    const server = spawn('php', ['-S', `127.0.0.1:${port}`, '-t', 'public', router], { cwd: root, env, windowsHide: true, stdio: 'ignore' });
    t.after(() => server.kill());
    const executablePath = [process.env.PUPPETEER_EXECUTABLE_PATH, puppeteer.executablePath(), 'C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(p => typeof p === 'string' && existsSync(p));
    const browser = await puppeteer.launch({ headless: true, executablePath, args: ['--no-sandbox'] });
    t.after(() => browser.close());
    const page = await browser.newPage();
    await page.setRequestInterception(true);
    page.on('request', r => r.url().startsWith(base + '/') ? r.continue({ headers: { ...r.headers(), 'X-RM-GERENCIA-QA': token } }) : r.url().startsWith('data:') || r.url().startsWith('blob:') ? r.continue() : r.abort());
    await page.evaluateOnNewDocument(() => localStorage.setItem('remembermind-theme', 'light'));
    await page.emulateMediaFeatures([{ name: 'prefers-reduced-motion', value: 'reduce' }]);
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    t.after(async () => { await writeFile(path.join(output, 'browser-errors.json'), JSON.stringify(errors)); });
    const response = await page.goto(base + '/admin/personal-documentacion', { waitUntil: 'networkidle0' });
    assert.equal(response.status(), 200);
    await page.click('.rm-document-library .rm-view-toggle button:first-child');
    await page.waitForSelector('.rm-document-library__table',{visible:true});
    assert.equal(await page.$$eval('[data-documento-fila]', el => el.length), 3);
    const personas = await page.$$eval('#documentacion-persona option', options => options.map(o => ({ value: o.value, text: o.textContent })));
    const personaDos = personas.find(o => o.text.includes('Profesional de prueba 2'));
    assert.ok(personaDos);
    const click = async selector => { await page.$eval(selector, el => el.scrollIntoView({ block: 'center' })); await page.click(selector); await page.waitForNetworkIdle({ idleTime: 300 }); };
    const matrix = [];
    for (const width of [1440, 1280, 1024, 768, 390]) {
        await page.setViewport({ width, height: 1000 });
        const overflow = await page.evaluate(() => document.documentElement.scrollWidth - innerWidth);
        assert.ok(overflow <= 1, `${width}: sin overflow (${overflow})`);
        const filtros = await page.$eval('.rm-staff-documents__filters', el => {
            const fields = [...el.querySelectorAll('input, select')].map(f => ({ top: Math.round(f.getBoundingClientRect().top), width: f.getBoundingClientRect().width, height: f.getBoundingClientRect().height }));
            return { width: el.getBoundingClientRect().width, rows: new Set(fields.map(f => f.top)).size, fields };
        });
        if (filtros.width > 1050) assert.equal(filtros.rows, 1, 'Filtros en una fila en pantalla amplia');
        if (width === 390) assert.equal(filtros.rows, 3, 'Búsqueda y dos filas compactas en móvil');
        assert.ok(filtros.fields.every(f => f.width >= 120 && f.height >= 44), `Campos legibles y táctiles: ${width} ${JSON.stringify(filtros)}`);
        await page.screenshot({ path: path.join(output, `biblioteca-${width}.png`), fullPage: true });
        await click('.rm-document-library__table .rm-document-actions button');
        await page.waitForSelector('#personal-documento-vista-previa [role="dialog"]', { visible: true });
        await page.waitForFunction(() => !!document.activeElement?.closest('#personal-documento-vista-previa'));
        assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
        const frame = await page.$eval('.rm-staff-documents__preview iframe', el => ({ src: el.getAttribute('src'), width: el.getBoundingClientRect().width, title: el.title }));
        assert.match(frame.src, /\/admin\/personal-documentacion\/archivos\//);
        assert.ok(frame.width > 200 && frame.title.includes('PDF'));
        await page.screenshot({ path: path.join(output, `vista-previa-${width}.png`), fullPage: true });
        await page.keyboard.press('Escape');
        await page.waitForSelector('#personal-documento-vista-previa', { hidden: true });
        await page.waitForFunction(() => document.activeElement?.closest('.rm-staff-documents__actions'));
        matrix.push({ width, overflow, preview: true, keyboard: true });
    }
    await page.type('#documentacion-buscar', 'Profesional de prueba 2');
    await page.waitForFunction(() => document.querySelectorAll('.rm-document-library__table [data-documento-fila]').length === 1);
    assert.match(await page.$eval('.rm-document-library__table [data-documento-fila]', el => el.innerText), /Certificado de formación/);
    await page.select('#documentacion-estado', 'OBSERVADO');
    await page.waitForFunction(() => document.querySelector('main')?.innerText.includes('No hay archivos con estos filtros'));
    await click('button[wire\\:click="limpiarFiltros"]');
    await page.waitForFunction(() => document.querySelectorAll('.rm-document-library__table [data-documento-fila]').length === 3);
    await page.select('#documentacion-persona', personaDos.value);
    await page.waitForFunction(() => document.querySelectorAll('.rm-document-library__table [data-documento-fila]').length === 1);
    assert.match(await page.$eval('.rm-document-library__table [data-documento-fila]', el => el.innerText), /Certificado de formación/);
    await page.select('#documentacion-formato', 'IMAGEN');
    await page.waitForFunction(() => document.querySelector('main')?.innerText.includes('No hay archivos con estos filtros'));
    await click('button[wire\\:click="limpiarFiltros"]');
    await page.waitForFunction(() => document.querySelectorAll('.rm-document-library__table [data-documento-fila]').length === 3);
    assert.equal(await page.$eval('#documentacion-persona', el => el.value), '');
    assert.equal(await page.$eval('#documentacion-formato', el => el.value), '');
    await click('button[wire\\:click="cambiarVista(\'solicitudes\')"]');
    assert.match(await page.$eval('main', el => el.innerText), /Sin solicitudes en esta consulta/);
    assert.equal(await page.$('button[wire\\:click="nuevaSolicitud"]'), null);

    assert.equal(await page.$('#solicitud-nombre'), null);
    assert.deepEqual(errors, []);
    await writeFile(path.join(output, 'qa.json'), JSON.stringify({ matrix, filters: true, solicitudes: true, errors }, null, 2));
});
