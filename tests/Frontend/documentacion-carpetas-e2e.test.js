import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { createServer } from 'node:net';
import { randomBytes } from 'node:crypto';
import { writeFile, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import puppeteer from 'puppeteer';

test('Documentación: tabla compartida, carpetas, miniaturas privadas y cinco anchos', { timeout: 240000 }, async t => {
    const root = fileURLToPath(new URL('../../', import.meta.url));
    const output = path.join(root, 'output', 'documentacion-carpetas-20261106');
    await mkdir(output, { recursive: true });
    const db = path.join(tmpdir(), `remembermind-gerencia-${randomBytes(8).toString('hex')}_testing.sqlite`);
    await writeFile(db, '', { flag: 'wx', mode: 0o600 });
    const port = await new Promise(resolve => { const s = createServer().listen(0, '127.0.0.1', () => { const p = s.address().port; s.close(() => resolve(p)); }); });
    const base = `http://127.0.0.1:${port}`;
    const token = randomBytes(24).toString('hex');
    const env = { ...process.env, APP_ENV: 'testing', APP_URL: base, RM_GERENCIA_QA_DB: db, RM_GERENCIA_QA_TOKEN: token, RM_GERENCIA_QA_AMPLIACION: '1', RM_GERENCIA_QA_ARCHIVOS: '1', RM_GERENCIA_QA_CARPETAS: '1' };
    const router = 'tests/Support/ServidorGerenciaSintetico.php';
    const prepared = await new Promise((resolve, reject) => {
        const c = spawn('php', [router, '--preparar'], { cwd: root, env, windowsHide: true });
        let out = ''; c.stdout.on('data', b => out += b); c.stderr.on('data', b => out += b);
        c.on('error', reject); c.on('close', code => code ? reject(new Error(out)) : resolve(out));
    });
    assert.match(prepared, /PREPARADO/);
    const server = spawn('php', ['-S', `127.0.0.1:${port}`, '-t', 'public', router], { cwd: root, env, windowsHide: true, stdio: 'ignore' });
    t.after(() => server.kill());
    const executablePath = [process.env.PUPPETEER_EXECUTABLE_PATH, puppeteer.executablePath(), 'C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(p => typeof p === 'string' && existsSync(p));
    const browser = await puppeteer.launch({ headless: true, executablePath, args: ['--no-sandbox'] });
    t.after(() => browser.close());
    const page = await browser.newPage();
    await page.setRequestInterception(true);
    page.on('request', r => r.url().startsWith(base + '/') ? r.continue({ headers: { ...r.headers(), 'X-RM-GERENCIA-QA': token } }) : r.url().startsWith('data:') || r.url().startsWith('blob:') ? r.continue() : r.abort());
    await page.evaluateOnNewDocument(() => localStorage.setItem('remembermind-theme', 'light'));
    await page.emulateMediaFeatures([{ name: 'prefers-reduced-motion', value: 'reduce' }]);
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    t.after(async () => { await writeFile(path.join(output, 'browser-errors.json'), JSON.stringify(errors)); });
    const response = await page.goto(base + '/admin/personal-documentacion', { waitUntil: 'networkidle0' });
    assert.equal(response.status(), 200);
    const click = async selector => { await page.$eval(selector, el => el.scrollIntoView({ block: 'center' })); await page.click(selector); await page.waitForNetworkIdle({ idleTime: 300 }); };
    const matrix=[];
    for(const width of [1440,1280,1024,768,390]) {
        await page.setViewport({width,height:1000});
        await page.goto(base+'/admin/personal-documentacion',{waitUntil:'networkidle0'});
        await page.waitForSelector('[data-carpeta-usuario]',{visible:true});
        assert.equal(await page.$$eval('[data-carpeta-usuario]',e=>e.length),3,'Una carpeta por persona, no por archivo');
        assert.equal(await page.$$eval('.rm-document-folder__body',e=>new Set(e.map(e=>getComputedStyle(e).backgroundColor)).size),1,'Carpetas neutras');
        assert.ok(await page.$eval('.rm-document-folder',e=>e.getBoundingClientRect().width)<=281,'Carpetas sin estirarse');
        assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
        await page.screenshot({path:path.join(output,'usuarios-'+width+'.png'),fullPage:true});
        const id=await page.$eval('[data-carpeta-usuario]',e=>e.dataset.carpetaUsuario);
        await click('[data-carpeta-usuario]');
        await page.waitForSelector('.rm-document-library__back',{visible:true});
        await page.waitForFunction(()=>document.getElementById('archivos-personal-titulo')===document.activeElement);
        assert.equal(await page.$$eval('[data-documento-fila]',e=>e.length),2,'Misma persona contiene sus dos archivos');
        assert.match(await page.$eval('#archivos-personal-titulo',e=>e.innerText),/Profesional de prueba 1/);
        const image=await page.waitForSelector('.rm-document-library__table .rm-document-thumb img',{visible:true});
        await page.waitForFunction(()=>[...document.querySelectorAll('.rm-document-library__table img')].every(i=>i.complete&&i.naturalWidth>0));
        assert.match(await image.evaluate(e=>e.src),/personal-documentacion\/archivos\//);
        assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
        await page.screenshot({path:path.join(output,'expediente-'+width+'.png'),fullPage:true});
        await click('.rm-document-library__table .rm-document-actions button');
        await page.waitForSelector('#personal-documento-vista-previa [role="dialog"]',{visible:true});
        await page.keyboard.press('Escape');await page.waitForSelector('#personal-documento-vista-previa',{hidden:true});
        await page.waitForFunction(()=>document.activeElement?.closest('.rm-document-library__table')&&document.activeElement?.getClientRects().length);
        await click('.rm-document-library__back');
        await page.waitForSelector('[data-carpeta-usuario]',{visible:true});
        await page.waitForFunction(id=>document.activeElement?.dataset.carpetaUsuario===id,{},id);
        await click('.rm-document-library .rm-view-toggle button:first-child');
        await page.waitForSelector('.rm-document-library__table',{visible:true});
        assert.equal(await page.$$eval('[data-documento-fila]',e=>e.length),4,'Tabla global conserva todos los archivos autorizados');
        await page.type('#documentacion-buscar','Certificado de formación');
        await page.waitForFunction(()=>document.querySelectorAll('[data-documento-fila]').length===1);
        await click('button[wire\\:click="limpiarFiltros"]');
        await page.waitForFunction(()=>document.querySelectorAll('[data-documento-fila]').length===4);
        matrix.push({width,userFolders:true,isolatedFile:true,thumbnail:true,focus:true});
    }
    assert.deepEqual(errors,[]);await writeFile(path.join(output,'qa-expedientes.json'),JSON.stringify({matrix,errors},null,2));
});
