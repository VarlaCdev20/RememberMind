import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { createServer } from 'node:net';
import { randomBytes } from 'node:crypto';
import { writeFile, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import puppeteer from 'puppeteer';

test('resultado guardado: gráficas fieles, datos paginados y acceso contextual en cinco tamaños', { skip: process.env.RM_GUARDADO_E2E !== '1', timeout: 240000 }, async t => {
    const root = fileURLToPath(new URL('../../', import.meta.url));
    const output = path.join(root, 'output', 'frontend-experto-guardado-20261119');
    await mkdir(output, { recursive: true });
    const db = path.join(tmpdir(), `remembermind-experto-${randomBytes(8).toString('hex')}_testing.sqlite`);
    await writeFile(db, '', { flag: 'wx', mode: 0o600 });
    const port = await new Promise(resolve => { const s = createServer().listen(0, '127.0.0.1', () => { const p = s.address().port; s.close(() => resolve(p)); }); });
    const base = `http://127.0.0.1:${port}`;
    const env = { ...process.env, APP_ENV: 'testing', APP_URL: base, RM_EXPERTO_DB: db, RM_EXPERTO_TOKEN: randomBytes(24).toString('hex'), RM_EXPERTO_FASE: 'resultado-guardado' };
    const router = 'tests/Support/ServidorExpertoSintetico.php';
    const prepared = await new Promise((resolve, reject) => {
        const c = spawn('php', [router, '--preparar'], { cwd: root, env, windowsHide: true });
        let out = ''; c.stdout.on('data', b => out += b); c.stderr.on('data', b => out += b);
        c.on('error', reject); c.on('close', code => code ? reject(new Error(out)) : resolve(out));
    });
    assert.match(prepared, /PREPARADO/);
    const server = spawn('php', ['-S', `127.0.0.1:${port}`, '-t', 'public', router], { cwd: root, env, windowsHide: true, stdio: 'ignore' });
    t.after(() => server.kill());
    const executablePath = [process.env.PUPPETEER_EXECUTABLE_PATH, puppeteer.executablePath(), 'C:/Program Files/Google/Chrome/Application/chrome.exe'].find(p => typeof p === 'string' && existsSync(p));
    const browser = await puppeteer.launch({ headless: true, executablePath, args: ['--no-sandbox'] });
    t.after(() => browser.close());
    const page = await browser.newPage();
    await page.setRequestInterception(true);
    page.on('request', r => r.url().startsWith(base) || r.url().startsWith('data:') ? r.continue() : r.abort());
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.setExtraHTTPHeaders({ 'X-RM-Experto': env.RM_EXPERTO_TOKEN, 'X-RM-Actor': 'ENF' });
    await page.evaluateOnNewDocument(() => localStorage.setItem('remembermind-theme', 'light'));
    const url = base + '/admin/enfermeria/pacientes/RES_QA_EXPERTO/resultados-experto';
    assert.equal((await page.goto(url, { waitUntil: 'networkidle0' })).status(), 200);
    await page.waitForSelector('.rm-stored-expert');
    assert.match(await page.$eval('#resultado-guardado-titulo', el => el.textContent), /Posible DCL amnésico multidominio/);
    assert.equal(await page.$eval('.rm-cognitive-status-chart__segment[data-status="alterado"]', el => el.getAttribute('stroke-dasharray')), '40 100');
    assert.equal(await page.$eval('.rm-stored-expert__details > details', el => el.open), false);
    const matrix = [];
    for (const width of [1440, 1280, 1024, 768, 390]) {
        await page.setViewport({ width, height: 1000 });
        await page.goto(url, { waitUntil: 'networkidle0' });
        await page.waitForNetworkIdle({ idleTime: 300 });
        if (width < 768) {
            await page.keyboard.press('Escape');
            await page.waitForFunction(() => document.querySelector('.rm-sidebar').getBoundingClientRect().right <= 1);
        }
        await page.$eval('.rm-expert-history', el => el.scrollIntoView({ block: 'start' }));
        const metrics = await page.evaluate(() => ({ overflow: document.documentElement.scrollWidth - innerWidth, title: parseFloat(getComputedStyle(document.querySelector('#resultado-guardado-titulo')).fontSize) }));
        assert.ok(metrics.overflow <= 1, `${width}: overflow ${metrics.overflow}`);
        assert.ok(metrics.title >= 25, `${width}: título legible (${metrics.title}px)`);
        assert.doesNotMatch(await page.$eval('.rm-stored-expert', el => el.innerText), /@else|@endif|\bnull\b|NaN|undefined|Infinity|\[object Object\]/);
        await page.screenshot({ path: path.join(output, `resultado-${width}.png`), fullPage: true });
        matrix.push({ width, ...metrics });
        await page.$eval('.rm-stored-expert__requirements', el => el.scrollIntoView({ block: 'center' }));
        await page.screenshot({ path: path.join(output, `fundamento-${width}.png`), fullPage: true });
    }
    await page.$eval('.rm-cognitive-status-chart__choice', el => el.focus());
    await page.keyboard.press('Tab'); await page.keyboard.press('Enter');
    await page.waitForFunction(() => document.querySelectorAll('.rm-cognitive-status-chart__choice')[1].getAttribute('aria-pressed') === 'true');
    await page.emulateMediaFeatures([{ name: 'prefers-reduced-motion', value: 'reduce' }]);
    await page.evaluate(() => { document.documentElement.classList.add('dark'); document.documentElement.setAttribute('data-theme', 'dark'); });
    await page.screenshot({ path: path.join(output, 'oscuro-390.png'), fullPage: true });
    await page.evaluate(() => { document.documentElement.classList.remove('dark'); document.documentElement.setAttribute('data-theme', 'light'); });
    await page.$eval('.rm-stored-expert__evidence > summary', el => el.click());
    await page.waitForFunction(() => document.querySelectorAll('.rm-stored-expert__table tbody tr').length === 8);
    const first = await page.$eval('.rm-stored-expert__table tbody', el => el.textContent);
    await page.$eval('[aria-label="Datos siguientes"]', el => el.click());
    await page.waitForFunction(first => document.querySelector('.rm-stored-expert__table tbody').textContent !== first, {}, first);
    await page.type('#guardado-buscar', 'memoria');
    await page.waitForFunction(() => document.querySelector('.rm-stored-expert__pager').textContent.includes('1 /'));
    assert.ok(await page.$eval('.rm-stored-expert__table tbody', el => el.textContent.toLowerCase().includes('memoria')));
    await page.screenshot({ path: path.join(output, 'evidencias-390.png'), fullPage: true });
    const evidenceLayout = await page.evaluate(() => ({ bottom: document.querySelector('.rm-stored-expert__table').getBoundingClientRect().bottom, pagerTop: document.querySelector('.rm-stored-expert__pager').getBoundingClientRect().top }));
    assert.ok(evidenceLayout.bottom <= evidenceLayout.pagerTop, 'El paginador aparece después de los datos, sin superposición');
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await page.$eval('#guardado-buscar', el => { el.value = 'inexistente-qa'; el.dispatchEvent(new Event('input', { bubbles: true })); });
    await page.waitForFunction(() => document.querySelectorAll('.rm-stored-expert__table tbody tr').length === 0);
    assert.equal((await page.goto(base + '/admin/enfermeria/pacientes/RES_QA_AJENO/resultados-experto', { waitUntil: 'networkidle0' })).status(), 404);
    await page.setExtraHTTPHeaders({ 'X-RM-Experto': env.RM_EXPERTO_TOKEN, 'X-RM-Actor': 'PSI' });
    assert.equal((await page.goto(base + '/admin/psicologia/residente/RES_QA_AJENO/resultados-experto', { waitUntil: 'networkidle0' })).status(), 200);
    assert.match(await page.$eval('#resultado-guardado-titulo', el => el.textContent), /Aún no se puede establecer/);
    assert.equal(await page.$eval('.rm-cognitive-status-chart__segment[data-status="insuficiente"]', el => el.getAttribute('stroke-dasharray')), '100 100');
    await page.screenshot({ path: path.join(output, 'abstencion-390.png'), fullPage: true });
    assert.deepEqual(errors, []);
    await writeFile(path.join(output, 'qa.json'), JSON.stringify({ matrix, errors, distribucion: '2 alteradas / 3 esperadas', paginacion: true, accesoAjeno: 404 }, null, 2));
});
