import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { createServer } from 'node:net';
import { randomBytes } from 'node:crypto';
import { writeFile, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import puppeteer from 'puppeteer';

test('Red de apoyo: residente, contactos, tabla y cinco anchos', { timeout: 240000 }, async t => {
    const root = fileURLToPath(new URL('../../', import.meta.url));
    const output = path.join(root, 'output', 'red-apoyo-visual-20261106');
    await mkdir(output, { recursive: true });
    const db = path.join(tmpdir(), `remembermind-gerencia-${randomBytes(8).toString('hex')}_testing.sqlite`);
    await writeFile(db, '', { flag: 'wx', mode: 0o600 });
    const port = await new Promise(resolve => { const s = createServer().listen(0, '127.0.0.1', () => { const p = s.address().port; s.close(() => resolve(p)); }); });
    const base = `http://127.0.0.1:${port}`;
    const token = randomBytes(24).toString('hex');
    const env = { ...process.env, APP_ENV: 'testing', AVISOS_PLANIFICACION_HABILITADOS: 'false', APP_URL: base, RM_GERENCIA_QA_DB: db, RM_GERENCIA_QA_TOKEN: token, RM_GERENCIA_QA_AMPLIACION: '1', RM_GERENCIA_QA_HISTORIA: '1', RM_GERENCIA_QA_RED_APOYO: '1' };
    const router = 'tests/Support/ServidorGerenciaSintetico.php';
    const prepared = await new Promise((resolve, reject) => {
        const c = spawn('php', [router, '--preparar'], { cwd: root, env, windowsHide: true });
        let out = ''; c.stdout.on('data', b => out += b); c.stderr.on('data', b => out += b);
        c.on('error', reject); c.on('close', code => code ? reject(new Error(out)) : resolve(out));
    });
    assert.match(prepared, /PREPARADO/);
    const server = spawn('php', ['-S', `127.0.0.1:${port}`, '-t', 'public', router], { cwd: root, env, windowsHide: true, stdio: 'ignore' });
    t.after(() => server.kill());
    const executablePath = [process.env.PUPPETEER_EXECUTABLE_PATH, puppeteer.executablePath(), 'C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(p => typeof p === 'string' && existsSync(p));
    const browser = await puppeteer.launch({ headless: true, executablePath, args: ['--no-sandbox'] });
    t.after(() => browser.close());
    const page = await browser.newPage();
    await page.setRequestInterception(true);
    page.on('request', r => r.url().startsWith(base + '/') ? r.continue({ headers: { ...r.headers(), 'X-RM-GERENCIA-QA': token } }) : r.url().startsWith('data:') || r.url().startsWith('blob:') ? r.continue() : r.abort());
    await page.evaluateOnNewDocument(() => localStorage.setItem('remembermind-theme', 'light'));
    await page.emulateMediaFeatures([{ name: 'prefers-reduced-motion', value: 'reduce' }]);
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    t.after(async () => { await writeFile(path.join(output, 'browser-errors.json'), JSON.stringify(errors)); });
    const response = await page.goto(base + '/admin/familia-social/red-apoyo', { waitUntil: 'networkidle0' });
    assert.equal(response.status(), 200);

    const click = async selector => { await page.$eval(selector,e=>e.scrollIntoView({block:'center'})); await page.click(selector); await page.waitForNetworkIdle({idleTime:300}); };
    const first = await page.$eval('#familia-residente', e => [...e.options].find(o=>o.textContent.includes('Persona de prueba')).value);
    const empty = await page.$eval('#familia-residente', e => [...e.options].find(o=>o.value && !o.textContent.includes('Persona de prueba')).value);
    for(const width of [1440,1280,1024,768,390]) {
        await page.setViewport({width,height:1000});
        await page.goto(base+'/admin/familia-social/red-apoyo?residente='+first,{waitUntil:'networkidle0'});
        await page.waitForSelector('.rm-support-network',{visible:true});
        assert.equal(await page.$$eval('[data-vinculo-nodo]',e=>e.length),3);
        const text=await page.$eval('.rm-support-network',e=>e.innerText);
        for(const label of ['Hija','Hijo','Amistad','Responsable principal','Contacto de emergencia','Vínculo inactivo','No acreditada']) assert.ok(text.includes(label),label);
        assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false,'Red sin desbordamiento');
        await page.screenshot({path:path.join(output,'red-'+width+'.png'),fullPage:true});
        await click('.rm-support-view-tools .rm-view-toggle button:last-child');
        await page.waitForSelector('.rm-support-table',{visible:true});
        assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false,'Tabla sin desbordamiento');
        assert.ok(await page.$$eval('.rm-support-table tbody tr', rows => rows.every(r => r.scrollHeight <= r.clientHeight + 2)), 'Filas de vínculos sin contenido superpuesto');
        await page.screenshot({path:path.join(output,'tabla-'+width+'.png'),fullPage:true});
        await click('.rm-support-view-tools .rm-view-toggle button:first-child');
        await click('.rm-support-contact__manage summary');
        await click('.rm-support-network button[wire\\:click^="editarContacto("]');
        await page.waitForSelector('#contacto-nombres',{visible:true});
        await page.screenshot({path:path.join(output,'editar-'+width+'.png'),fullPage:true});
        page.once('dialog',d=>d.accept());
        await click('button[wire\\:click="cerrarContacto"]');
        await page.waitForSelector('#familia-contacto-formulario',{hidden:true});
        await page.select('#familia-residente',empty);
        await page.waitForFunction(()=>document.querySelector('.rm-support-network')?.innerText.includes('Sin vínculos registrados'));
        await page.screenshot({path:path.join(output,'sin-vinculos-'+width+'.png'),fullPage:true});
        await click("button[wire\\:click=\"cambiarVista('personas')\"]");
        await page.waitForFunction(()=>!document.querySelector('#familia-residente'));
        assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false,'Personas sin desbordamiento');
        assert.ok(await page.$$eval('.rm-support-workspace tbody tr', rows => rows.every(r => r.scrollHeight <= r.clientHeight + 2)), 'Filas de personas sin contenido superpuesto');
        await page.screenshot({path:path.join(output,'personas-'+width+'.png'),fullPage:true});
    }
    assert.deepEqual(errors,[]);
});
