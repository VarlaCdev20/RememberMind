import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { createServer } from 'node:net';
import { randomBytes } from 'node:crypto';
import { writeFile, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import puppeteer from 'puppeteer';

test('informe de Enfermería: composición, popup, panel lateral y acceso contextual', { skip: process.env.RM_ENFERMERIA_INFORME_E2E !== '1', timeout: 240000 }, async t => {
    const root = fileURLToPath(new URL('../../', import.meta.url));
    const output = path.join(root, 'output', 'frontend-experto-enfermeria-20261104');
    await mkdir(output, { recursive: true });
    const db = path.join(tmpdir(), `remembermind-experto-${randomBytes(8).toString('hex')}_testing.sqlite`);
    await writeFile(db, '', { flag: 'wx', mode: 0o600 });
    const port = await new Promise(resolve => { const s = createServer().listen(0, '127.0.0.1', () => { const p = s.address().port; s.close(() => resolve(p)); }); });
    const base = `http://127.0.0.1:${port}`;
    const env = { ...process.env, APP_ENV: 'testing', APP_URL: base, RM_EXPERTO_DB: db, RM_EXPERTO_TOKEN: randomBytes(24).toString('hex') };
    const router = 'tests/Support/ServidorExpertoSintetico.php';
    const prepared = await new Promise((resolve, reject) => {
        const c = spawn('php', [router, '--preparar'], { cwd: root, env, windowsHide: true });
        let out = ''; c.stdout.on('data', b => out += b); c.stderr.on('data', b => out += b);
        c.on('error', reject); c.on('close', code => code ? reject(new Error(out)) : resolve(out));
    });
    assert.match(prepared, /PREPARADO/);
    const server = spawn('php', ['-S', `127.0.0.1:${port}`, '-t', 'public', router], { cwd: root, env, windowsHide: true, stdio: 'ignore' });
    t.after(() => server.kill());
    const executablePath = [process.env.PUPPETEER_EXECUTABLE_PATH, puppeteer.executablePath(), 'C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(p => typeof p === 'string' && existsSync(p));
    const browser = await puppeteer.launch({ headless: true, executablePath, args: ['--no-sandbox'] });
    t.after(() => browser.close());
    const page = await browser.newPage();
    await page.setRequestInterception(true);
    page.on('request', r => r.url().startsWith(base) || r.url().startsWith('data:') ? r.continue() : r.abort());
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.setExtraHTTPHeaders({ 'X-RM-Experto': env.RM_EXPERTO_TOKEN, 'X-RM-Actor': 'ENF' });
    await page.evaluateOnNewDocument(() => localStorage.setItem('remembermind-theme', 'light'));
    const response = await page.goto(base + '/admin/enfermeria/pacientes/RES_QA_EXPERTO/resultados-experto', { waitUntil: 'networkidle0' });
    assert.equal(response.status(), 200);
    const click = async selector => { await page.$eval(selector, el => el.scrollIntoView({ block: 'center' })); await page.click(selector); await page.waitForNetworkIdle({ idleTime: 300 }); };
    const matrix = [];
    for (const width of [1440, 1280, 1024, 768, 390]) {
        await page.setViewport({ width, height: 1000 });
        await page.waitForFunction(() => document.querySelector('.rm-expert-report__result'));
        const metrics = await page.evaluate(() => ({ overflow: document.documentElement.scrollWidth - innerWidth, size: parseFloat(getComputedStyle(document.querySelector('#expert-nursing-today-title')).fontSize), identityCount: document.querySelectorAll('.rm-expert-report__identity').length }));
        await page.screenshot({ path: path.join(output, `informe-${width}.png`), fullPage: true });
        assert.ok(metrics.overflow <= 1, `${width}: sin scroll horizontal (${metrics.overflow})`);
        assert.ok(metrics.size >= 26, `${width}: resultado legible (${metrics.size}px)`);
        assert.equal(metrics.identityCount, 1);
        assert.equal(await page.$('.rm-expert-report .rm-expert-reading-nav'), null);
        await page.screenshot({ path: path.join(output, `informe-${width}.png`), fullPage: true });
        matrix.push({ width, ...metrics });
        await page.$eval('#nursing-evolution-heading', el => el.scrollIntoView({ block: 'start' }));
        await page.screenshot({ path: path.join(output, `evolucion-${width}.png`), fullPage: true });
        await page.$eval('.rm-expert-report__hero', el => el.scrollIntoView({ block: 'start' }));
    }
    await click('.rm-expert-report__result button[wire\\:click="abrirSignificado"]');
    await page.waitForFunction(() => [...document.querySelectorAll('[role="dialog"]')].some(el => el.getClientRects().length && el.innerText.includes('¿Qué significa este resultado?')));
    await page.waitForFunction(() => !!document.activeElement?.closest('[role="dialog"]'));
    await page.screenshot({ path: path.join(output, 'popup-390.png'), fullPage: true });
    await page.keyboard.press('Escape'); await page.waitForNetworkIdle({ idleTime: 300 });
    await page.setViewport({ width: 1440, height: 1000 });
    await click('.rm-expert-report__result button[wire\\:click="abrirConsulta(\'registro\')"]');
    await page.waitForFunction(() => document.querySelector('.rm-drawer-shell--docked.is-open'));
    const positions = await page.evaluate(() => ({ report: document.querySelector('.rm-expert-results').getBoundingClientRect().right, drawer: document.querySelector('.rm-drawer-shell--docked.is-open aside').getBoundingClientRect().left }));
    assert.ok(positions.report <= positions.drawer + 1, 'El panel no tapa el informe');
    await page.screenshot({ path: path.join(output, 'evidencias-1440.png'), fullPage: true });
    await page.keyboard.press('Escape'); await page.waitForNetworkIdle({ idleTime: 300 });
    await click('.rm-expert-report__result a[href="#expert-nursing-fundamento"]');
    assert.equal(await page.$eval('#expert-nursing-fundamento', el => el.open), true);
    const denied = await page.goto(base + '/admin/enfermeria/pacientes/RES_QA_AJENO/resultados-experto', { waitUntil: 'networkidle0' });
    assert.equal(denied.status(), 404);
    assert.deepEqual(errors, []);
    await writeFile(path.join(output, 'qa.json'), JSON.stringify({ matrix, errors, popup: true, panelLateral: positions, accesoAjeno: denied.status() }, null, 2));
});
